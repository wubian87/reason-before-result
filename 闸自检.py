# ---------------- 打印用的中文对齐小工具 ----------------

def 显示宽(文本):
    """按终端显示宽度计数：中日韩全角字符算 2，其余算 1。"""
    return sum(2 if unicodedata.east_asian_width(字) in ("W", "F") else 1 for 字 in 文本)


def 补空(文本, 目标宽):
    return 文本 + " " * max(0, 目标宽 - 显示宽(文本))


def 打印逐条表格(用例, 结果):
    """把某个用例的七条判罚打成中文表格，给人看「闸拦下了一笔不该过的单」的证据。"""
    print(f"── 用例 {用例['编号']}（{用例['说明']}）：闸的完整判罚，共 {len(结果['逐条'])} 条 ──")
    行集 = [("规则", "名", "判", "说明")]
    行集 += [(条["规则"], 条["名"], "过" if 条["过"] else "拦", 条["说明"]) for 条 in 结果["逐条"]]
    列宽 = [max(显示宽(行[列]) for 行 in 行集) for 列 in range(3)]
    表头行 = (补空("规则", 列宽[0]) + "  " + 补空("名", 列宽[1]) + "  "
              + 补空("判", 列宽[2]) + "  " + "说明")
    print(表头行)
    print("─" * 显示宽(表头行))
    for 条 in 结果["逐条"]:
        print(补空(条["规则"], 列宽[0]) + "  " + 补空(条["名"], 列宽[1]) + "  "
              + 补空("过" if 条["过"] else "拦", 列宽[2]) + "  " + 条["说明"])


