# ---------------- 打印用的中文对齐小工具 ----------------

def 显示宽(文本):
    """按终端显示宽度计数：中日韩全角字符算 2，其余算 1。"""
    return sum(2 if unicodedata.east_asian_width(字) in ("W", "F") else 1 for 字 in 文本)


def 补空(文本, 目标宽):
    return 文本 + " " * max(0, 目标宽 - 显示宽(文本))


def 打印逐条表格(用例, 结果):
    """把某个用例的七条判罚打成中文表格，给人看「闸拦下了一笔不该过的单」的证据。"""
    print(f"-- Case {用例['编号']} ({用例['说明']}): all {len(结果['逐条'])} receipts --")
    行集 = [("RULE", "NAME", "VERDICT", "WHY")]
    行集 += [(条["规则"], 条["名"], "PASS" if 条["过"] else "STOP", 条["说明"]) for 条 in 结果["逐条"]]
    列宽 = [max(显示宽(行[列]) for 行 in 行集) for 列 in range(3)]
    表头行 = (补空("RULE", 列宽[0]) + "  " + 补空("NAME", 列宽[1]) + "  "
              + 补空("VERDICT", 列宽[2]) + "  " + "WHY")
    print(表头行)
    print("─" * 显示宽(表头行))
    for 条 in 结果["逐条"]:
        print(补空(条["规则"], 列宽[0]) + "  " + 补空(条["名"], 列宽[1]) + "  "
              + 补空("PASS" if 条["过"] else "STOP", 列宽[2]) + "  " + 条["说明"])


# ---------------- 主流程 ----------------

def 主函数():
    print("Options order gate - offline self-test (hard-coded fixtures, no network)")
    print(f"Fixed clock: today is {今天}, market open")
    print()
    结果表 = []
    不符数 = 0
    for 用例 in 用例表:
        结果 = 过闸(用例["提案"], 用例["账户"], 用例["时钟"])
        结果表.append((用例, 结果))
        实际 = "过" if 结果["过"] else "拦"  # 内部判词，⛔ 与期望字段同一套
        规则判 = {条["规则"]: 条["过"] for 条 in 结果["逐条"]}
        # 断言：结论与期望一致；被拦的还要拦在期望的那条规则上；七条账目一条不少。
        断言 = (实际 == 用例["期望"]
                and len(结果["逐条"]) == 7
                and (用例["期望规则"] is None or 规则判.get(用例["期望规则"]) is False))
        if not 断言:
            不符数 += 1
        判语 = "MATCH" if 断言 else "MISMATCH"
        英 = {"过": "release", "拦": "stop"}
        print(f"Case {用例['编号']} | {用例['说明']} | expected: {英[用例['期望']]}, "
              f"got: {英[实际]} -> {判语}")
        if 实际 == "拦":
            print(f"   {结果['一句话']}")
    print()
    总数 = len(用例表)
    print(f"Total: {总数} cases, {总数 - 不符数} matched, {不符数} mismatched")
    print()
    # 附证：用例 2（裸卖）的完整七条判罚。
    用例二, 结果二 = 结果表[1]
    打印逐条表格(用例二, 结果二)
    return 0 if 不符数 == 0 else 1


if __name__ == "__main__":
    sys.exit(主函数())
